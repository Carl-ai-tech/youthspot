def plan_lines(p: dict) -> list[str]:
    """卡片 detail 與提示詞共用的文字列。"""
    out = []
    for y in p["years"]:
        out.append(f"{y['year']}｜{y['goal']}　看：{'；'.join(y['watch'])}")
        out.append("　　做：" + "；".join(f"{who}（{role}）{what}" for who, role, what in y["actions"]))
    return out
