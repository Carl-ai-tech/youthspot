def lookup(question: str) -> list[dict]:
    """問題裡碰到哪些議題，回傳對應的權責列（給提示詞用）。"""
    import re
    q = question.replace("台", "臺")
    return [j for j in JURISDICTION if re.search(j["pattern"], q)]


